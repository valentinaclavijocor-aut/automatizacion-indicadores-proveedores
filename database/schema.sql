BEGIN;

-- 1. PROVEEDORES: cada empresa tiene un NIT único.
CREATE TABLE proveedores (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit      VARCHAR(20) NOT NULL UNIQUE,
    nombre   VARCHAR(150) NOT NULL,
    correo   VARCHAR(150) NOT NULL UNIQUE,
    activo   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT proveedores_nit_no_vacio CHECK (btrim(nit) <> ''),
    CONSTRAINT proveedores_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT proveedores_correo_valido CHECK (
        correo ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
    )
);

-- 2. USUARIOS: solo los roles previstos en el contrato API.
-- Los hashes se generan FUERA de PostgreSQL; nunca se guarda la clave original.
CREATE TABLE usuarios (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(150) NOT NULL,
    correo        VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol           VARCHAR(20) NOT NULL,
    proveedor_id  INTEGER NULL,
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT usuarios_proveedor_fk
        FOREIGN KEY (proveedor_id) REFERENCES proveedores(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT usuarios_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT usuarios_correo_valido CHECK (
        correo ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
    ),
    CONSTRAINT usuarios_hash_argon2id CHECK (password_hash LIKE '$argon2id$%' AND char_length(password_hash) >= 80),
    CONSTRAINT usuarios_rol_valido CHECK (rol IN ('ADMIN', 'PROVEEDOR')),
    CONSTRAINT usuarios_rol_proveedor_coherente CHECK (
        (rol = 'ADMIN' AND proveedor_id IS NULL)
        OR
        (rol = 'PROVEEDOR' AND proveedor_id IS NOT NULL)
    )
);

-- 3. PUBLICACIONES: un solo registro por período YYYY-MM.
CREATE TABLE publicaciones (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo           VARCHAR(7) NOT NULL UNIQUE,
    fecha_publicacion TIMESTAMP NULL,
    estado            VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    CONSTRAINT publicaciones_periodo_valido CHECK (
        periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
    ),
    CONSTRAINT publicaciones_estado_valido CHECK (
        estado IN ('BORRADOR', 'PUBLICADO')
    ),
    CONSTRAINT publicaciones_fecha_coherente CHECK (
        (estado = 'BORRADOR' AND fecha_publicacion IS NULL)
        OR
        (estado = 'PUBLICADO' AND fecha_publicacion IS NOT NULL)
    )
);

-- 4. INDICADORES: valor numérico por proveedor y publicación.
CREATE TABLE indicadores (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id   INTEGER NOT NULL,
    publicacion_id INTEGER NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    valor          NUMERIC(12,2) NOT NULL,
    unidad         VARCHAR(30) NOT NULL,
    CONSTRAINT indicadores_proveedor_fk
        FOREIGN KEY (proveedor_id) REFERENCES proveedores(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT indicadores_publicacion_fk
        FOREIGN KEY (publicacion_id) REFERENCES publicaciones(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT indicadores_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT indicadores_unidad_no_vacia CHECK (btrim(unidad) <> '')
);

-- 5. NOTIFICACIONES: estado del intento de aviso por proveedor y período.
-- Un registro por proveedor/publicación; los reintentos actualizan ese registro.
CREATE TABLE notificaciones (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id   INTEGER NOT NULL,
    publicacion_id INTEGER NOT NULL,
    correo_destino VARCHAR(150) NOT NULL,
    fecha_envio    TIMESTAMP NULL,
    estado         VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    error          TEXT NULL,
    CONSTRAINT notificaciones_proveedor_fk
        FOREIGN KEY (proveedor_id) REFERENCES proveedores(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT notificaciones_publicacion_fk
        FOREIGN KEY (publicacion_id) REFERENCES publicaciones(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT notificaciones_unica_por_proveedor
        UNIQUE (proveedor_id, publicacion_id),
    CONSTRAINT notificaciones_estado_valido CHECK (
        estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')
    ),
    CONSTRAINT notificaciones_intento_coherente CHECK (
        (estado = 'PENDIENTE' AND fecha_envio IS NULL AND error IS NULL)
        OR
        (estado = 'ENVIADO' AND fecha_envio IS NOT NULL AND error IS NULL)
        OR
        (estado = 'FALLIDO' AND fecha_envio IS NOT NULL AND error IS NOT NULL
         AND btrim(error) <> '')
    )
);

-- Los correos se comparan sin distinguir mayúsculas y minúsculas.
-- Los UNIQUE de cada tabla mantienen el contrato y estos índices adicionales
-- bloquean también duplicados como DEMO@EJEMPLO.COM vs demo@ejemplo.com.
CREATE UNIQUE INDEX uq_proveedores_correo_normalizado
    ON proveedores (lower(btrim(correo)));
CREATE UNIQUE INDEX uq_usuarios_correo_normalizado
    ON usuarios (lower(btrim(correo)));

-- Índices para las consultas comunes de FastAPI.
CREATE INDEX idx_usuarios_proveedor_id ON usuarios (proveedor_id);
CREATE INDEX idx_indicadores_proveedor_publicacion
    ON indicadores (proveedor_id, publicacion_id);
CREATE INDEX idx_indicadores_publicacion_id ON indicadores (publicacion_id);
CREATE INDEX idx_notificaciones_publicacion_id ON notificaciones (publicacion_id);
CREATE INDEX idx_notificaciones_estado ON notificaciones (estado);

-- Regla: los indicadores solo se agregan, editan o eliminan mientras su
-- publicación esté en BORRADOR (también impide mover uno ya publicado).
CREATE FUNCTION verificar_indicadores_en_borrador()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    estado_actual VARCHAR(20);
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        SELECT estado INTO estado_actual
        FROM publicaciones WHERE id = OLD.publicacion_id FOR SHARE;
        IF estado_actual IS DISTINCT FROM 'BORRADOR' THEN
            RAISE EXCEPTION 'No se pueden modificar indicadores de una publicación ya publicada';
        END IF;
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        SELECT estado INTO estado_actual
        FROM publicaciones WHERE id = NEW.publicacion_id FOR SHARE;
        IF estado_actual IS DISTINCT FROM 'BORRADOR' THEN
            RAISE EXCEPTION 'Solo se pueden registrar indicadores en publicaciones BORRADOR';
        END IF;
        RETURN NEW;
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_indicadores_borrador
BEFORE INSERT OR UPDATE OR DELETE ON indicadores
FOR EACH ROW EXECUTE FUNCTION verificar_indicadores_en_borrador();

-- Regla: publicación solo pasa de BORRADOR a PUBLICADO cuando tiene indicadores.
-- Fecha incluida en la misma transacción (sin agregar campos nuevos).
CREATE FUNCTION verificar_publicacion()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.estado = 'PUBLICADO' AND (
        NEW.estado IS DISTINCT FROM OLD.estado OR
        NEW.fecha_publicacion IS DISTINCT FROM OLD.fecha_publicacion
    ) THEN
        RAISE EXCEPTION 'No se puede modificar el estado o fecha de una publicación ya publicada';
    END IF;

    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        IF OLD.estado <> 'BORRADOR' OR NEW.estado <> 'PUBLICADO' THEN
            RAISE EXCEPTION 'Solo se permite publicar una vez, desde BORRADOR';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM indicadores i WHERE i.publicacion_id = NEW.id
        ) THEN
            RAISE EXCEPTION 'No se puede publicar un período sin indicadores';
        END IF;
        NEW.fecha_publicacion := COALESCE(
            NEW.fecha_publicacion, CURRENT_TIMESTAMP::TIMESTAMP
        );
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_verificar_publicacion
BEFORE UPDATE OF estado, fecha_publicacion ON publicaciones
FOR EACH ROW EXECUTE FUNCTION verificar_publicacion();

-- Una publicación nueva siempre inicia en BORRADOR. Para publicar debe
-- existir el flujo de UPDATE, donde se valida que ya tenga indicadores.
CREATE FUNCTION exigir_nueva_publicacion_borrador()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado <> 'BORRADOR' OR NEW.fecha_publicacion IS NOT NULL THEN
        RAISE EXCEPTION 'Una publicación nueva debe empezar en BORRADOR, sin fecha';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_nueva_publicacion_borrador
BEFORE INSERT ON publicaciones
FOR EACH ROW EXECUTE FUNCTION exigir_nueva_publicacion_borrador();

-- Regla del contrato: publicar genera UNA notificación pendiente por cada
-- proveedor ACTIVO presente en ese período. No se envían correos desde SQL.
CREATE FUNCTION crear_notificaciones_al_publicar()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.estado = 'BORRADOR' AND NEW.estado = 'PUBLICADO' THEN
        INSERT INTO notificaciones (
            proveedor_id, publicacion_id, correo_destino,
            fecha_envio, estado, error
        )
        SELECT DISTINCT p.id, NEW.id, p.correo, NULL, 'PENDIENTE', NULL
        FROM indicadores i
        JOIN proveedores p ON p.id = i.proveedor_id
        WHERE i.publicacion_id = NEW.id AND p.activo = TRUE
        ON CONFLICT (proveedor_id, publicacion_id) DO NOTHING;
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_notificaciones_al_publicar
AFTER UPDATE OF estado ON publicaciones
FOR EACH ROW EXECUTE FUNCTION crear_notificaciones_al_publicar();

COMMIT;
